const assert=require('node:assert/strict');
const {build}=require('../static/office_state.js');
const team={id:'ทีม A',workType:'coding',agents:[{id:'engineer',skills:['review']},{id:'content-editor',skills:[]}]};
const run=(status,project='shop',updated_at=10)=>({team:'ทีม A',agent:'engineer',status,engine:'Codex',project,updated_at});
assert.equal(build(team,[],true)[0].state,'idle');
assert.equal(build(team,[],false)[0].state,'unknown');
assert.equal(build(team,[run('working')],true)[0].activity,'computer');
assert.equal(build(team,[],true)[1].activity,'writing');
assert.equal(build(team,[run('waiting')],true)[0].state,'waiting');
assert.equal(build(team,[run('unknown')],true)[0].state,'unknown');
assert.equal(build(team,[run('failed')],true)[0].state,'failed');
assert.equal(build(team,[run('closed')],true)[0].state,'idle');
assert.equal(build(team,[run('done','old',50),run('working','new',10)],true)[0].state,'working');
assert.deepEqual(build(team,[run('working','shop'),run('waiting','launch')],true)[0].projects,['shop','launch']);
assert.equal(build(team,[{...run('working'),team:'Other'}],true)[0].state,'idle');
assert.equal(build(team,[run('working')],false)[0].state,'unknown');
assert.equal(build(team,[run('done')],true)[0].project,null);
assert.deepEqual(build(team,[],true)[0].skills,['review']);
assert.deepEqual(build({...team,agents:[]},[],true),[]);
assert.equal(build({...team,agents:[{id:'ice',displayName:'ไอซ์',role:'Developer'}]},[],true)[0].displayName,'ไอซ์');
assert.equal(build({...team,agents:[{id:'ice',displayName:'ไอซ์',role:'Developer'}]},[],true)[0].role,'Developer');
console.log('Pixel Office state checks passed');
